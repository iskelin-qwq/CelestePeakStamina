using System.Collections.Generic;
using Monocle;

namespace Celeste.Mod.PeakStamina;

// ============================================================================
//  Session：一次游戏流程内的数据
//
//  它的生命周期是"从进入游戏到退出游戏"（或者切关卡时重置），
//  所以正好用来放"会随游戏进程变化、但不需要永久存进存档"的数值。
//
//  体力上限就属于这种：这一局摔伤了上限就掉了，重开一关应该恢复原样。
//  如果哪天你想让上限跨存档永久保存，就把它挪到 PeakStaminaModuleSaveData。
//
//  ⚠️ 重要：Everest 会把这份数据存到
//      Saves\<存档名>-modsession-PeakStamina.celeste
//  并在下次启动 / 切换存档时加载回来。也就是说——
//
//      字段初始值只在"Session 对象刚构造出来"的那一瞬间有效，
//      紧接着就会被存档里的旧值覆盖掉。
//
//  所以千万不能依赖初始值来保证进图满上限。
//  真正负责"每张图开局把上限补满"的是 StaminaTracker.ResetMaxStamina()，
//  它在关卡加载后由 StaminaTracker.Update 调用，时序在存档载入之后。
// ============================================================================
public class PeakStaminaModuleSession : EverestModuleSession {
    // ------------------------------------------------------------------
    //  伤害向量
    // ------------------------------------------------------------------
    //  存放所有"永久扣掉体力上限"的伤害。
    //  每种类型只占一个条目，同类伤害会自动累加到同一条上。
    //  顺序 = 首次受到该类型伤害的顺序，体力条按这个顺序渲染。
    //
    //  ★ 这里是唯一记录"上限被扣了多少"的地方。
    //    体力上限不再单独存一个数，而是由下面的 StaminaCap 算出来，
    //    这样就不可能出现"伤害表和上限对不上"的状态。
    public List<Damage> Damages { get; set; } = new List<Damage>();

    // ------------------------------------------------------------------
    //  当前体力上限（派生值，不要直接赋值）
    // ------------------------------------------------------------------
    //  体力上限 = 基础上限 110 − 所有伤害之和
    //
    //  下限 StaminaCapFloor 取 0，它同时是【致死阈值】的一部分：
    //  致死判定是"伤害 >= 当前上限 − 下限"，代入 0 就是"伤害 >= 当前上限"。
    //
    //  因为只有 伤害 < 上限 才会活下来，所以存活时上限最小是 1，
    //  这里用 Max(..., 0) 只是让公式在极端数据下也不会算出负数。
    //
    //  所有对上限的修改都应该走 StaminaTracker.TakeDamage() /
    //  ResetMaxStamina()，不要在这里或别处直接改。
    public float StaminaCap =>
        Calc.Max(StaminaTracker.BaseMaxStamina - DamageAccumulator.Total(Damages),
                 StaminaTracker.StaminaCapFloor);
}
